#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""PostToolUse: после записи в .bpd/ прогнать валидатор.

Зачем хук, а не просьба в тексте навыка. Просьбу «не забудь проверить»
выполняют, пока помнят. Хук исполняется кодом и помнить не обязан — это
разница между «мы договорились» и «так устроено».

Молчит, когда всё чисто: сторож, который отмечается после каждой записи,
превращается в шум и его перестают читать.

Говорит вслух в трёх случаях: нашлись проблемы (код 1), прогон не состоялся
(код 2) и «ответил кодом, которого у валидатора нет». Последнее — не мелочь:
такой исход значит, что чинить надо команду прогона, а не проект.
"""

from __future__ import annotations

import os
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from _common import (  # noqa: E402
    МЕТКА, прочитать_событие, проект, сказать, сломался, это_bpd_проект,
)

СОБЫТИЕ = "PostToolUse"
ПИШУЩИЕ = ("Write", "Edit", "MultiEdit", "NotebookEdit")
ПОТОЛОК = 4000      # столько символов отчёта кладём в контекст
МЕДЛЕННО = 5.0      # дольше — предупреждаем про налог на каждую запись
ТАЙМАУТ = 120


def внутри(путь: str, папка: str) -> bool:
    """Файл лежит внутри папки. Регистр складываем: macOS и Windows не различают."""
    try:
        общий = os.path.commonpath([os.path.realpath(путь), os.path.realpath(папка)])
    except (ValueError, OSError):
        return False
    return общий.casefold() == os.path.realpath(папка).casefold()


def main() -> None:
    событие = прочитать_событие()
    if событие.get("tool_name") not in ПИШУЩИЕ:
        return

    корень = проект(событие)
    if not это_bpd_проект(корень):
        return  # Не BPD-проект — не наше дело.

    записан = (событие.get("tool_input") or {}).get("file_path") or ""
    if not записан or not внутри(записан, os.path.join(корень, МЕТКА)):
        return  # Писали не в память проекта.

    валидатор = os.path.join(os.environ.get("CLAUDE_PLUGIN_ROOT", ""), "bin", "bpd-validate")
    if not os.path.isfile(валидатор):
        сказать(СОБЫТИЕ,
                f"Проверка BPD не выполнена: валидатор не найден по пути {валидатор}. "
                f"Это не «всё чисто». Похоже, плагин установлен не полностью.")
        return

    начало = time.time()
    try:
        прогон = subprocess.run(
            [валидатор, корень],
            capture_output=True, timeout=ТАЙМАУТ,
            encoding="utf-8", errors="replace",
            env=dict(os.environ, PYTHONIOENCODING="utf-8"),
        )
    except subprocess.TimeoutExpired:
        сказать(СОБЫТИЕ, f"Проверка BPD не уложилась в {ТАЙМАУТ} с и была прервана. "
                         f"Это не «всё чисто»: проверка не выполнялась.")
        return
    except OSError as беда:
        сказать(СОБЫТИЕ, f"Проверку BPD не удалось запустить ({беда}). "
                         f"Это не «всё чисто». Часто помогает: chmod +x {валидатор}")
        return

    if прогон.returncode == 0:
        return  # Зелёный молчит.

    if прогон.returncode == 1:
        шапка = ("Валидатор BPD нашёл проблемы в .bpd/ (код 1). "
                 "Разбери их сейчас, пока правка свежая.")
    elif прогон.returncode == 2:
        шапка = ("Валидатор BPD НЕ СОСТОЯЛСЯ (код 2). "
                 "Это не «всё чисто» — проверка не выполнена.")
    else:
        шапка = (f"Валидатор BPD ответил кодом {прогон.returncode}, а такого исхода "
                 f"у него нет (есть 0, 1, 2). Прогон НЕ СОСТОЯЛСЯ: чинить надо "
                 f"команду прогона, а не проект.")

    отчёт = ((прогон.stdout or "") + (прогон.stderr or "")).strip()
    if len(отчёт) > ПОТОЛОК:
        отчёт = отчёт[:ПОТОЛОК] + "\n… отчёт обрезан, полностью: bpd-validate"

    ушло = time.time() - начало
    хвост = (f"\n\n(проверка заняла {ушло:.1f} с — это налог на каждую запись "
             f"в .bpd/; если мешает, хук можно выключить)") if ушло > МЕДЛЕННО else ""

    сказать(СОБЫТИЕ, f"{шапка}\n\n{отчёт}{хвост}")


if __name__ == "__main__":
    try:
        main()
    except Exception as беда:  # noqa: BLE001 — тихо умирать хук не вправе
        сломался(__file__, беда, СОБЫТИЕ)
    sys.exit(0)
