#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Валидатор папки .bpd/ — механическая проверка проекта BPD.

До этого файла все правила BPD были просьбами к модели: «нумеруй так»,
«не пиши RESULT.md раньше времени», «вердикт одним словом». Просьбу можно
нечаянно нарушить, и никто не заметит — пока статус этапа не соврёт.
Здесь просьбы становятся приборами.

ВАЖНО. Валидатор асимметричен: ошибками он ловит только ЗАВЫШЕНИЕ доверия —
то, из-за чего проект выглядит здоровее, чем есть (этап принят без результата,
файл заявлен, но его нет). Всё, что требует человеческого суждения, идёт
предупреждением и код выхода не роняет.

`exit 0` означает «заявленное непротиворечиво», а НЕ «проект в порядке»:
хороша ли работа по существу, машина не знает и знать не может.

Коды возврата:
    0 — ошибок нет
    1 — найдены ошибки
    2 — прогон НЕ СОСТОЯЛСЯ (нечего проверять, не прочитали, упали)

Код 2 существует затем, чтобы невыполненная проверка не была неотличима
от пройденной. Молчание никогда не значит «всё хорошо».

Запуск:  bpd-validate [папка проекта]      (по умолчанию — текущая)
"""

from __future__ import annotations

import glob
import json
import os
import re
import subprocess
import sys

ПРОВЕРКИ = 21  # столько блоков ниже; сверяется тестом

for поток in (sys.stdout, sys.stderr):
    try:
        поток.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError, OSError):
        pass

ошибок = 0
предупреждений = 0

ЗАДАЧА = re.compile(r"^\s*[-*]\s*\[([ xX])\]")
ПЛЕЙСХОЛДЕР = re.compile(r"\{\{[^}]*\}\}")
ИМЯ_ПАПКИ = re.compile(r"^\d{2}(\.\d+)?-[a-z0-9]+(-[a-z0-9]+)*$")
ВЕРДИКТЫ = ("Принято", "Доработать")


def сдаться(строки: list[str]) -> None:
    print()
    for с in строки:
        print(с, file=sys.stderr)
    print("    Это НЕ «в проекте всё чисто»: проверки не выполнялись.", file=sys.stderr)
    sys.exit(2)


def ошибка(заголовок: str, строки: list[str]) -> None:
    global ошибок
    ошибок += 1
    print(f"❌ {заголовок} ({len(строки)}):")
    for с in строки:
        print(f"    • {с}")
    print()


def предупредить(заголовок: str, строки: list[str]) -> None:
    global предупреждений
    предупреждений += 1
    print(f"⚠️  {заголовок} ({len(строки)}):")
    for с in строки:
        print(f"    • {с}")
    print()


def ок(текст: str) -> None:
    print(f"✅ {текст}")


def читать(путь: str) -> str:
    """Прочитать файл. Не смогли — это код 2, а не «проверка прошла»."""
    try:
        with open(путь, encoding="utf-8") as ф:
            return ф.read()
    except UnicodeDecodeError:
        сдаться([f"ОШИБКА: {путь} не читается как UTF-8.",
                 "    Файлы BPD должны быть в UTF-8; этот, похоже, в другой кодировке."])
    except OSError as беда:
        сдаться([f"ОШИБКА: не прочитать {путь}: {беда}"])
    return ""


def раздел(текст: str, заголовок: str) -> str | None:
    """Тело раздела `## Заголовок` до следующего заголовка того же уровня.

    Именно раздела, а не всего файла: вердикт «Доработать» встречается
    в пояснениях шаблона, и поиск по файлу объявил бы непринятым каждый
    принятый этап (`rules.md` § 3).
    """
    начало = re.search(rf"^##\s+{re.escape(заголовок)}\s*$", текст, re.M)
    if not начало:
        return None
    хвост = текст[начало.end():]
    следующий = re.search(r"^##\s", хвост, re.M)
    return хвост[: следующий.start()] if следующий else хвост


def строки_таблицы(тело: str) -> list[list[str]]:
    """Ячейки строк markdown-таблицы без шапки и разделителя."""
    собрано = []
    for строка in тело.split("\n"):
        обрезана = строка.strip()
        if not обрезана.startswith("|"):
            continue
        ячейки = [я.strip() for я in обрезана.strip("|").split("|")]
        if all(re.fullmatch(r":?-{2,}:?", я) for я in ячейки if я):
            continue
        собрано.append(ячейки)
    return собрано


def живая(ячейки: list[str]) -> bool:
    """Строка таблицы с настоящими данными, а не шаблонная рыба."""
    склеено = " ".join(ячейки)
    return bool(склеено.strip("—- ")) and not ПЛЕЙСХОЛДЕР.search(склеено)


def корни(текст: str) -> set[str]:
    """Значимые слова, обрезанные до пяти букв.

    Обрезаем, потому что русский склоняется: «раздела» в отчёте и «разделы»
    в PROJECT.md — одно слово, а дословное сравнение считает их разными.
    """
    return {с[:5] for с in re.findall(r"[а-яёa-z0-9]{5,}", текст.lower())}


def похоже_доехало(решение: str, куда: str) -> bool:
    """Решение из отчёта узнаётся в PROJECT.md, пусть и переформулированное.

    Дословного совпадения не ждём: команда переносит решение короче, и это
    правильно. Сторож, который кричит на нормальную работу, читать перестают —
    проверено на живой фикстуре 12.08.2026.
    """
    свои = корни(решение)
    if len(свои) < 3:
        return True  # Слишком коротко, чтобы судить.
    общих = len(свои & корни(куда))
    return общих / len(свои) >= 0.4


class Этап:
    def __init__(self, номер: str, название: str, папка: str | None):
        self.номер = номер
        self.название = название
        self.папка = папка
        self.отменён = False

    def файл(self, имя: str) -> str | None:
        if not self.папка:
            return None
        путь = os.path.join(self.папка, имя)
        return путь if os.path.isfile(путь) else None

    def задачи(self) -> tuple[int, int, list[str]]:
        """(закрыто, всего, боксы вне раздела «Задачи»)."""
        план = self.файл("PLAN.md")
        if not план:
            return 0, 0, []
        закрыто = всего = 0
        чужие = []
        текущий = "(до первого заголовка)"
        for номер, строка in enumerate(читать(план).split("\n"), 1):
            if строка.startswith("## "):
                текущий = строка[3:].strip()
                continue
            совпало = ЗАДАЧА.match(строка)
            if not совпало:
                continue
            if текущий != "Задачи":
                чужие.append(f"{os.path.basename(self.папка or '')}/PLAN.md:{номер} "
                             f"— бокс в разделе «{текущий}»")
                continue
            всего += 1
            if совпало.group(1).lower() == "x":
                закрыто += 1
        return закрыто, всего, чужие

    def вердикт(self) -> str | None:
        """Слово из раздела «## Итог», как есть. None — раздела нет."""
        проверка = self.файл("CHECK.md")
        if not проверка:
            return None
        тело = раздел(читать(проверка), "Итог")
        if тело is None:
            return ""
        осмысленные = [с.strip() for с in тело.split("\n")
                       if с.strip() and not с.strip().startswith(">")]
        return осмысленные[0].strip("*_ ") if осмысленные else ""


def main() -> int:
    корень = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
    if not os.path.isdir(корень):
        сдаться([f"ОШИБКА: папки {корень} не существует.",
                 "    Часто это опечатка в пути — сверьте с тем, что на диске."])
    bpd = os.path.join(корень, ".bpd")
    if not os.path.isdir(bpd):
        сдаться([f"ОШИБКА: в {корень} нет папки .bpd/ — проверять нечего.",
                 "    Это не BPD-проект, либо вы запустили проверку не там.",
                 "    Завести проект: /bpd:start"])

    print(f"🔍 Валидатор BPD\n   Проект: {корень}\n")

    # ── подготовка: карта, папки, конфиг ────────────────────────────────────
    карта_путь = os.path.join(bpd, "ROADMAP.md")
    if not os.path.isfile(карта_путь):
        сдаться(["ОШИБКА: нет .bpd/ROADMAP.md — без карты проверять нечего.",
                 "    Карта появляется при /bpd:start; если её удалили — восстановите."])
    карта = читать(карта_путь)

    активные = [(я[0], я[1]) for я in строки_таблицы(раздел(карта, "Этапы") or "")
                if len(я) >= 2 and re.fullmatch(r"\d{1,3}(\.\d+)?", я[0])]
    отменённые = [(я[0], я[1]) for я in строки_таблицы(раздел(карта, "Отменённые этапы") or "")
                  if len(я) >= 2 and re.fullmatch(r"\d{1,3}(\.\d+)?", я[0])]

    папки = sorted(п for п in glob.glob(os.path.join(bpd, "stages", "*"))
                   if os.path.isdir(п))

    этапы: list[Этап] = []
    двойники: list[str] = []
    for номер, название in активные + отменённые:
        найдено = [п for п in папки if os.path.basename(п).split("-")[0] == номер]
        if len(найдено) > 1:
            двойники.append(f"этап {номер}: {', '.join(os.path.basename(п) for п in найдено)}")
        этап = Этап(номер, название, найдено[0] if найдено else None)
        этап.отменён = (номер, название) in отменённые
        этапы.append(этап)

    # ── 1. глоб по номеру находит ровно одну папку (rules.md § 2) ──────────
    if двойники:
        ошибка("ДВЕ ПАПКИ НА ОДИН НОМЕР — все три команды цикла встанут", двойники)
    else:
        ок("Номер этапа находит ровно одну папку")

    # ── 2. квадратные скобки только у задач (rules.md § 3) ─────────────────
    чужие_боксы = [с for э in этапы for с in э.задачи()[2]]
    if чужие_боксы:
        ошибка("ГАЛОЧКИ ВНЕ РАЗДЕЛА «ЗАДАЧИ» — счёт закрытых задач их поймает, "
               "и этап залипнет в «в работе»", чужие_боксы)
    else:
        ок("Квадратные скобки в PLAN.md есть только у задач")

    # ── 3. вердикт — ровно одно из двух слов (rules.md § 3) ────────────────
    кривые = []
    for э in этапы:
        в = э.вердикт()
        if в is None:
            continue
        if в not in ВЕРДИКТЫ:
            кривые.append(f"этап {э.номер}: в разделе «## Итог» стоит "
                          f"{в!r} вместо «Принято» или «Доработать»")
    if кривые:
        ошибка("ВЕРДИКТ НЕ РАСПОЗНАН — этап остаётся без статуса вовсе", кривые)
    else:
        ок("Вердикты этапов распознаются")

    # ── 4. RESULT.md только когда все задачи закрыты (rules.md § 3) ────────
    рано = []
    встали = []
    for э in этапы:
        закрыто, всего, _ = э.задачи()
        if э.файл("RESULT.md") and всего and закрыто < всего:
            рано.append(f"этап {э.номер}: закрыто {закрыто} из {всего}, "
                        f"а RESULT.md уже создан")
        if not э.файл("RESULT.md") and всего and закрыто == всего:
            встали.append(f"этап {э.номер}: все {всего} задач закрыты, а RESULT.md нет")
    if рано:
        ошибка("RESULT.md СОЗДАН РАНЬШЕ ВРЕМЕНИ — статус покажет «выполнен» "
               "посреди работы", рано)
    else:
        ок("RESULT.md появляется только после закрытия всех задач")
    if встали:
        предупредить("РАБОТА ВСТАЛА НА ОТЧЁТЕ — задачи закрыты, отчёта нет", встали)

    # ── 5. заявленные файлы существуют на диске ────────────────────────────
    призраки = []
    for э in этапы:
        отчёт = э.файл("RESULT.md")
        if not отчёт:
            continue
        тело = раздел(читать(отчёт), "Созданные и изменённые файлы")
        if тело is None:
            continue
        for ячейки in строки_таблицы(тело):
            if len(ячейки) < 2 or not живая(ячейки) or ячейки[0].lower() == "файл":
                continue
            заявлен = ячейки[0].strip("`").strip()
            if not заявлен or заявлен.startswith(("http", "—")):
                continue
            if not os.path.exists(os.path.join(корень, заявлен)):
                призраки.append(f"этап {э.номер}: заявлен {заявлен}, а на диске его нет")
    if призраки:
        ошибка("ЗАЯВЛЕН ФАЙЛ, КОТОРОГО НЕТ — отчёт это заявление, а не доказательство",
               призраки)
    else:
        ок("Все заявленные файлы есть на диске")

    # ── 6. порядок появления файлов (rules.md § 3) ─────────────────────────
    порядок = []
    for э in этапы:
        if э.файл("RESULT.md") and not э.файл("PLAN.md"):
            порядок.append(f"этап {э.номер}: RESULT.md есть, а PLAN.md нет — "
                           f"результат без плана")
        if э.файл("CHECK.md") and not э.файл("RESULT.md"):
            порядок.append(f"этап {э.номер}: CHECK.md есть, а RESULT.md нет — "
                           f"проверять было нечего")
    if порядок:
        ошибка("ФАЙЛЫ ЭТАПА ПОЯВИЛИСЬ НЕ В ТОМ ПОРЯДКЕ", порядок)
    else:
        ок("Файлы этапов появляются в правильном порядке")

    # ── 7. карта и папки совпадают ─────────────────────────────────────────
    расхождения = []
    номера_карты = {н for н, _ in активные + отменённые}
    for э in этапы:
        if э.папка is None:
            расхождения.append(f"этап {э.номер} «{э.название}» есть в карте, а папки нет")
    for п in папки:
        номер = os.path.basename(п).split("-")[0]
        if номер not in номера_карты:
            расхождения.append(f"папка {os.path.basename(п)} есть, а этапа в карте нет")
    if расхождения:
        ошибка("КАРТА РАЗОШЛАСЬ С ДИСКОМ", расхождения)
    else:
        ок("Каждому этапу карты соответствует папка, и наоборот")

    # ── 8. имя папки этапа по формату (rules.md § 2) ───────────────────────
    кривые_имена = []
    for п in папки:
        имя = os.path.basename(п)
        if not ИМЯ_ПАПКИ.match(имя):
            беда = "нет ведущего нуля" if re.match(r"^\d[-.]", имя) else "не тот формат"
            кривые_имена.append(f"{имя} — {беда}, ждём NN-imya-latinicej")
    if кривые_имена:
        ошибка("ИМЯ ПАПКИ ЭТАПА НЕ ПО ФОРМАТУ — глоб по номеру её не найдёт",
               кривые_имена)
    else:
        ок("Имена папок этапов по формату")

    # ── 9. номера уникальны и не переиспользованы (rules.md § 6) ───────────
    все_номера = [н for н, _ in активные + отменённые]
    повторы = sorted({н for н in все_номера if все_номера.count(н) > 1})
    if повторы:
        ошибка("НОМЕР ЭТАПА ВЫДАН ДВАЖДЫ — номера вечные, переиспользовать нельзя",
               [f"номер {н} встречается {все_номера.count(н)} раза" for н in повторы])
    else:
        ок("Номера этапов уникальны")

    # ── 10. папка отменённого этапа не удалена (rules.md § 6) ──────────────
    потеряны = [f"этап {э.номер} «{э.название}» отменён, но и папки его нет — "
                f"результаты внутри пропали"
                for э in этапы if э.отменён and э.папка is None]
    if потеряны:
        ошибка("ПАПКА ОТМЕНЁННОГО ЭТАПА УДАЛЕНА", потеряны)
    else:
        ок("Папки отменённых этапов на месте")

    # ── 11. в ROADMAP.md нет колонки «Статус» (rules.md § 5) ───────────────
    шапка = [я for я in строки_таблицы(раздел(карта, "Этапы") or "")
             if я and я[0].strip("# ").lower() in ("#", "")]
    есть_статус = any("статус" in " ".join(я).lower() for я in шапка)
    if есть_статус:
        ошибка("В ROADMAP.md ЗАВЕЛАСЬ КОЛОНКА «СТАТУС»",
               ["Её никто не обновляет — она протухнет и начнёт спорить "
                "с вычисленным статусом."])
    else:
        ок("В ROADMAP.md нет колонки «Статус»")

    # ── 12. в STATE.md нет процентов и статусов (rules.md § 5) ─────────────
    состояние_путь = os.path.join(bpd, "STATE.md")
    состояние = читать(состояние_путь) if os.path.isfile(состояние_путь) else ""
    протухшее = [f"STATE.md:{н} — {с.strip()[:70]}"
                 for н, с in enumerate(состояние.split("\n"), 1)
                 if re.search(r"\d+\s*%", с) or re.search(r"[○◎◐●⚠✓✗]", с)]
    if протухшее:
        предупредить("В STATE.md ЗАПИСАН ПРОГРЕСС ИЛИ СТАТУС — он там протухнет",
                     протухшее)
    else:
        ок("В STATE.md нет процентов и статусов")

    # ── 13. STATE.md ведётся, следующий шаг назван ─────────────────────────
    if not состояние:
        предупредить("НЕТ .bpd/STATE.md", ["После /clear пользователю не за что зацепиться."])
    else:
        шаг = re.search(r"\*\*Следующий шаг:\*\*\s*(.+)", состояние)
        если_пусто = not шаг or not шаг.group(1).strip() or ПЛЕЙСХОЛДЕР.search(шаг.group(1))
        if если_пусто:
            предупредить("В STATE.md НЕ НАЗВАН СЛЕДУЮЩИЙ ШАГ",
                         ["Это первое, что читают, вернувшись через месяц."])
        else:
            ок("В STATE.md назван следующий шаг")

    # ── 14. решения доехали из RESULT.md в PROJECT.md (rules.md § 5) ───────
    проект_путь = os.path.join(bpd, "PROJECT.md")
    проект = читать(проект_путь) if os.path.isfile(проект_путь) else ""
    решения_проекта = раздел(проект, "Принятые решения") or ""
    не_доехали = []
    for э in этапы:
        отчёт = э.файл("RESULT.md")
        if not отчёт:
            continue
        тело = раздел(читать(отчёт), "Принятые решения")
        for ячейки in строки_таблицы(тело or ""):
            if len(ячейки) < 2 or not живая(ячейки) or ячейки[0].lower() == "решение":
                continue
            ключ = ячейки[0].strip("`* ").strip()
            if not похоже_доехало(ключ, решения_проекта):
                не_доехали.append(f"этап {э.номер}: «{ключ[:60]}» — есть в RESULT.md, "
                                  f"нет в PROJECT.md")
    if не_доехали:
        предупредить("РЕШЕНИЕ НЕ ДОЕХАЛО ДО PROJECT.md — а RESULT.md его не сохранит "
                     "для будущих этапов", не_доехали)
    else:
        ок("Решения из отчётов доехали до PROJECT.md")

    # ── 15. плейсхолдеры шаблона не остались в живых файлах ────────────────
    рыба = []
    for корень_обхода, _, файлы in os.walk(bpd):
        for имя in файлы:
            if not имя.endswith(".md"):
                continue
            полный = os.path.join(корень_обхода, имя)
            for номер, строка in enumerate(читать(полный).split("\n"), 1):
                if ПЛЕЙСХОЛДЕР.search(строка):
                    рыба.append(f"{os.path.relpath(полный, корень)}:{номер}")
    if рыба:
        ошибка("В ФАЙЛАХ ОСТАЛАСЬ ШАБЛОННАЯ РЫБА {{…}} — файл создан, но не заполнен",
               рыба[:20] + ([f"…и ещё {len(рыба) - 20}"] if len(рыба) > 20 else []))
    else:
        ок("Шаблонная рыба {{…}} нигде не осталась")

    # ── 16. config.json: набор ключей и машинные значения (rules.md § 7) ───
    конфиг_путь = os.path.join(bpd, "config.json")
    беды_конфига = []
    if not os.path.isfile(конфиг_путь):
        беды_конфига.append("файла нет вовсе")
    else:
        try:
            конфиг = json.loads(читать(конфиг_путь))
        except json.JSONDecodeError as беда:
            сдаться([f"ОШИБКА: .bpd/config.json не разбирается как JSON: {беда}"])
            конфиг = {}
        нужные = {"project_name", "scale", "mode", "use_subagents",
                  "features", "created", "bpd_version"}
        for ключ in sorted(нужные - set(конфиг)):
            беды_конфига.append(f"нет ключа {ключ}")
        for ключ in sorted(set(конфиг) - нужные):
            беды_конфига.append(f"лишний ключ {ключ} — его никто не читает")
        if конфиг.get("scale") not in ("fast", "medium", "large"):
            беды_конфига.append(f"scale = {конфиг.get('scale')!r}, "
                                f"а можно fast, medium или large")
        if конфиг.get("mode") not in ("interactive", "automatic"):
            беды_конфига.append(f"mode = {конфиг.get('mode')!r}, "
                                f"а можно interactive или automatic")
        if not isinstance(конфиг.get("use_subagents"), bool):
            беды_конфига.append("use_subagents должен быть true/false, а не строка")
        if not isinstance(конфиг.get("features"), dict):
            беды_конфига.append("features должен быть объектом (пустой {} — законно)")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(конфиг.get("created", ""))):
            беды_конфига.append(f"created = {конфиг.get('created')!r}, "
                                f"а ждём дату вида ГГГГ-ММ-ДД")
    if беды_конфига:
        ошибка("CONFIG.JSON НЕ ПО СХЕМЕ — команды будут ветвиться не туда",
               беды_конфига)
    else:
        ок("config.json по схеме, значения машинные")

    # ── 17. путь до плагина не записан в файлы проекта (rules.md § 1) ──────
    протухнет = []
    for корень_обхода, _, файлы in os.walk(bpd):
        for имя in файлы:
            полный = os.path.join(корень_обхода, имя)
            if "CLAUDE_PLUGIN_ROOT" in читать(полный):
                протухнет.append(os.path.relpath(полный, корень))
    if os.path.isfile(os.path.join(корень, "CLAUDE.md")) and \
            "CLAUDE_PLUGIN_ROOT" in читать(os.path.join(корень, "CLAUDE.md")):
        протухнет.append("CLAUDE.md")
    if протухнет:
        ошибка("ПУТЬ ДО ПЛАГИНА ЗАПИСАН В ФАЙЛ ПРОЕКТА — он меняется при обновлении",
               протухнет)
    else:
        ок("Путь до плагина нигде не записан в файлы проекта")

    # ── 18. счётчик в CHECK.md совпадает с реальным счётом ─────────────────
    вранья = []
    for э in этапы:
        проверка = э.файл("CHECK.md")
        if not проверка:
            continue
        тело = раздел(читать(проверка), "Задачи из плана")
        совпало = re.search(r"Закрыто:\s*(\d+)\s+из\s+(\d+)", тело or "")
        if not совпало:
            continue
        закрыто, всего, _ = э.задачи()
        if (int(совпало.group(1)), int(совпало.group(2))) != (закрыто, всего):
            вранья.append(f"этап {э.номер}: в CHECK.md «Закрыто: {совпало.group(1)} "
                          f"из {совпало.group(2)}», а в PLAN.md — {закрыто} из {всего}")
    if вранья:
        ошибка("СЧЁТЧИК В CHECK.md НЕ СХОДИТСЯ С PLAN.md", вранья)
    else:
        ок("Счётчики закрытых задач сходятся")

    # ── 19. «Принято» при незакрытых пунктах (skills/check § вердикт) ──────
    натяжки = []
    for э in этапы:
        if э.вердикт() != "Принято":
            continue
        проверка = э.файл("CHECK.md")
        текст = читать(проверка) if проверка else ""
        закрыто, всего, _ = э.задачи()
        причины = []
        if всего and закрыто < всего:
            причины.append(f"закрыто {закрыто} из {всего} задач")
        for имя_раздела in ("Заявленные файлы", "Чеклист качества",
                            "Критерии готовности из дорожной карты"):
            тело = раздел(текст, имя_раздела)
            for ячейки in строки_таблицы(тело or ""):
                if not живая(ячейки):
                    continue
                если_нет = [я for я in ячейки[1:] if я.strip().lower() in ("нет", "no")]
                if если_нет:
                    причины.append(f"в разделе «{имя_раздела}» есть «Нет»")
                    break
        if причины:
            натяжки.append(f"этап {э.номер}: «Принято», хотя " + "; ".join(причины))
    if натяжки:
        ошибка("ЭТАП ПРИНЯТ ПРИ НЕЗАКРЫТЫХ ПУНКТАХ — приёмка сама себе противоречит",
               натяжки)
    else:
        ок("Принятые этапы не имеют незакрытых пунктов")

    # ── 20. решения не осели в STATE.md вместо PROJECT.md (rules.md § 5) ───
    похоже_на_решение = [f"STATE.md:{н} — {с.strip()[:70]}"
                         for н, с in enumerate(состояние.split("\n"), 1)
                         if re.search(r"\b(потому что|так как|чтобы)\b", с)
                         and len(с.strip()) > 40]
    if похоже_на_решение:
        предупредить("ПОХОЖЕ, В STATE.md ЛЕЖИТ РЕШЕНИЕ — этот файл перезаписывают, "
                     "решениям место в PROJECT.md", похоже_на_решение)
    else:
        ок("Решения не осели в STATE.md")

    # ── 21. git: этапы принимаются, а коммитов нет (предупреждение) ────────
    принятых = sum(1 for э in этапы if э.вердикт() == "Принято")
    if принятых and os.path.isdir(os.path.join(корень, ".git")):
        try:
            вывод = subprocess.run(["git", "-C", корень, "status", "--porcelain"],
                                   capture_output=True, text=True, timeout=20,
                                   encoding="utf-8", errors="replace")
            грязно = [с for с in вывод.stdout.split("\n") if с.strip()]
        except (OSError, subprocess.SubprocessError):
            грязно = []
        if len(грязно) > 20:
            предупредить("ЭТАПЫ ПРИНИМАЮТСЯ, А ИЗМЕНЕНИЯ НЕ КОММИТЯТСЯ",
                         [f"незакоммиченных изменений: {len(грязно)}",
                          "Неудачный этап будет нечем откатить."])
        else:
            ок("Git: незакоммиченного хвоста не накопилось")
    else:
        ок("Git-проверка неприменима (проект не в git или принятых этапов нет)")

    # ── итог ────────────────────────────────────────────────────────────────
    статусы = {"принято": принятых, "всего этапов": len(активные),
               "отменено": len(отменённые)}
    print(f"\n📊 {', '.join(f'{к}: {з}' for к, з in статусы.items())}")
    print(f"   Проверок: {ПРОВЕРКИ}, предупреждений: {предупреждений}, ошибок: {ошибок}\n")

    if ошибок:
        print("🔴 Найдены проблемы — см. выше. Почини и прогони снова.")
        return 1
    print("🟢 Ошибок нет: заявленное непротиворечиво.")
    print("   Это НЕ значит «проект в порядке»: хороша ли работа по существу,")
    print("   машина не знает. Она проверила форму, а не содержание.")
    return 0


