# П1. Версия одна и та же в трёх местах
# Баг: три файла надо менять синхронно, ни один не выводится из другого.
# ────────────────────────────────────────────────────────────────────────────
def п1_версия() -> None:
    try:
        манифест = json.loads(читать(".claude-plugin/plugin.json"))
        конфиг = json.loads(читать("templates/config.json"))
    except json.JSONDecodeError as беда:
        сдаться(f"не разобрать JSON: {беда}")
        return
    найдено = {
        ".claude-plugin/plugin.json → version": манифест.get("version"),
        "templates/config.json → bpd_version": конфиг.get("bpd_version"),
    }
    старт = читать("skills/start/SKILL.md")
    в_старте = re.findall(r'"bpd_version"\s*:\s*"([^"]+)"', старт)
    for номер, значение in enumerate(в_старте, 1):
        найдено[f"skills/start/SKILL.md → bpd_version ({номер})"] = значение

    значения = set(найдено.values())
    if len(значения) == 1 and None not in значения:
        ок(f"Версия совпадает во всех трёх местах: {значения.pop()}")
    else:
        ошибка(
            "ВЕРСИИ РАЗОШЛИСЬ — при выпуске подняли не везде",
            [f"{где}: {что!r}" for где, что in найдено.items()],
        )


# ────────────────────────────────────────────────────────────────────────────
# П2. Фразы «шаблон уже загружен» быть не должно
# Баг Б1: субагент стартует с пустой головой, шаблона он не видит и выдумывает
# формат сам. Из-за этого весь режим «большой проект» работал вхолостую.
# ────────────────────────────────────────────────────────────────────────────
def п2_загружен_в_контексте(тексты: dict[str, str]) -> None:
    виновные = []
    for файл, текст in тексты.items():
        for номер, строка in enumerate(текст.split("\n"), 1):
            if "уже загружен" in строка and "неправда" not in строка.lower():
                виновные.append(f"{файл}:{номер}")
    if виновные:
        ошибка(
            "ВОЗВРАТ БАГА Б1: где-то снова обещано, что шаблон уже в контексте",
            виновные + ["Субагент видит только то, что написано в его промпте."],
        )
    else:
        ок("Нигде не обещано, что шаблон «уже загружен в контексте»")


# ────────────────────────────────────────────────────────────────────────────
# П3. В промпте каждого субагента — настоящие пути
# Вторая половина бага Б1: путь был выдуман и вёл не туда.
# ────────────────────────────────────────────────────────────────────────────
def п3_пути_в_промптах() -> None:
    беды = []
    for навык in ("plan", "do", "check"):
        текст = читать(f"skills/{навык}/SKILL.md")
        for блок in re.findall(r"Task\(\s*(.*?)\n\)", текст, re.S):
            if "${CLAUDE_PLUGIN_ROOT}/references/rules.md" not in блок:
                беды.append(f"skills/{навык}/SKILL.md: в промпте нет пути к rules.md")
            if "${CLAUDE_PLUGIN_ROOT}/templates/" not in блок:
                беды.append(f"skills/{навык}/SKILL.md: в промпте нет пути к шаблону")
    if беды:
        ошибка("ПРОМПТ СУБАГЕНТА БЕЗ ПУТЕЙ — он не найдёт ни правил, ни шаблона", беды)
    else:
        ок("В промптах субагентов есть настоящие пути к правилам и шаблонам")


# ────────────────────────────────────────────────────────────────────────────
# П4. config.json — только машинные значения
# Баг Б3: в конфиге лежало русское «интерактивный», а сравнивали с interactive.
# Условие не выполнялось ни при каком раскладе — режим не работал никогда.
# ────────────────────────────────────────────────────────────────────────────
КЛЮЧИ_КОНФИГА = {
    "project_name", "scale", "mode", "use_subagents",
    "features", "created", "bpd_version",
}
ЗНАЧЕНИЯ = {
    "scale": {"fast", "medium", "large"},
    "mode": {"interactive", "automatic"},
}
РУССКИЕ = ("быстрый", "средний", "большой", "интерактивный", "автоматический")


def п4_машинные_значения(тексты: dict[str, str]) -> None:
    беды = []
    try:
        конфиг = json.loads(читать("templates/config.json"))
    except json.JSONDecodeError as беда:
        сдаться(f"не разобрать templates/config.json: {беда}")
        return

    лишние = set(конфиг) - КЛЮЧИ_КОНФИГА
    нехватка = КЛЮЧИ_КОНФИГА - set(конфиг)
    if лишние:
        беды.append(f"лишние ключи: {', '.join(sorted(лишние))} — их никто не читает")
    if нехватка:
        беды.append(f"нет ключей: {', '.join(sorted(нехватка))}")
    for поле, допустимые in ЗНАЧЕНИЯ.items():
        if конфиг.get(поле) not in допустимые:
            беды.append(f"{поле} = {конфиг.get(поле)!r}, а можно только {sorted(допустимые)}")
    if not isinstance(конфиг.get("use_subagents"), bool):
        беды.append("use_subagents должен быть true/false, а не строка")
    if not isinstance(конфиг.get("features"), dict):
        беды.append("features должен быть объектом (пустой {} — законно)")

    # Сравнение с русским словом в условии — тот самый Б3. Строки-подписи для
    # экрана содержат стрелку «→» и под запрет не попадают.
    for файл, текст in тексты.items():
        for номер, строка in enumerate(текст.split("\n"), 1):
            if "→" in строка:
                continue
            if re.search(r"(scale|mode)\b", строка) and any(с in строка.lower() for с in РУССКИЕ):
                беды.append(f"{файл}:{номер} — сравнение настройки с русским словом")

    if беды:
        ошибка("ВОЗВРАТ БАГА Б3: настройки перестали быть машинными", беды)
    else:
        ок("Настройки машинные: значения из закрытых списков, русского в условиях нет")


# ────────────────────────────────────────────────────────────────────────────
# П5. Формула прогресса живёт в одном месте
# Баг Б2: формул было две, и они давали разные числа.
# ────────────────────────────────────────────────────────────────────────────
def п5_одна_формула(тексты: dict[str, str]) -> None:
    места = [ф for ф, т in тексты.items() if "завершённые этапы ÷" in т]
    if места == ["references/rules.md"]:
        ок("Формула прогресса записана ровно один раз — в rules.md")
    elif not места:
        ошибка("ФОРМУЛЫ ПРОГРЕССА НЕТ ВОВСЕ — её кто-то удалил", ["ищется в rules.md § 4"])
    else:
        ошибка(
            "ВОЗВРАТ БАГА Б2: формула прогресса записана больше одного раза",
            места + ["Копия обречена разойтись с оригиналом."],
        )


# ────────────────────────────────────────────────────────────────────────────
# П6. Квадратные скобки в шаблонах — только у задач
# Баг Б14, найденный живым прогоном: исполнитель проставил галочки и в чеклисте
# качества, счёт «сколько задач закрыто» поймал чужие, и этап залип навсегда.
# ────────────────────────────────────────────────────────────────────────────
БОКС = re.compile(r"^\s*[-*]\s*\[[ xX]\]")


def п6_боксы_только_у_задач() -> None:
    беды = []
    for имя in sorted(os.listdir(путь("templates"))):
        if not имя.endswith(".md"):
            continue
        текст = читать(f"templates/{имя}")
        текущий = "(до первого заголовка)"
        for номер, строка in enumerate(текст.split("\n"), 1):
            if строка.startswith("## "):
                текущий = строка[3:].strip()
            elif БОКС.match(строка) and текущий != "Задачи":
                беды.append(f"templates/{имя}:{номер} — бокс в разделе «{текущий}»")
    if беды:
        ошибка(
            "ВОЗВРАТ БАГА Б14: квадратные скобки завелись вне раздела «Задачи»",
            беды + ["Счёт закрытых задач поймает их и этап никогда не станет выполненным."],
        )
    else:
        ок("Квадратные скобки в шаблонах есть только у задач")


# ────────────────────────────────────────────────────────────────────────────
# П7. Таблица статусов в README совпадает с каноном в rules.md
# Найдено разбором: README показывал 5 статусов из 7 и врал про два.
# ────────────────────────────────────────────────────────────────────────────
ЗНАЧКИ = "○◎◐●⚠✓✗"


def п7_статусы_совпадают() -> None:
    канон = set()
    правила = раздел(читать("references/rules.md"), "## 3. Статус этапа. Единственная таблица")
    if правила is None:
        сдаться("в rules.md не найден раздел про статус этапа")
        return
    for строка in правила.split("\n"):
        ячейки = [я.strip() for я in строка.strip().strip("|").split("|")]
        if len(ячейки) == 4 and ячейки[3] and ячейки[3][0] in ЗНАЧКИ:
            канон.add((ячейки[3], ячейки[2]))

    в_readme = set()
    for строка in читать("README.md").split("\n"):
        ячейки = [я.strip() for я in строка.strip().strip("|").split("|")]
        if len(ячейки) == 2 and ячейки[1] and ячейки[1][0] in ЗНАЧКИ:
            значок, _, название = ячейки[1].partition(" ")
            в_readme.add((значок, название.strip()))

    if not канон:
        сдаться("не разобрать таблицу статусов в rules.md")
    if канон == в_readme:
        ок(f"Таблица статусов в README совпадает с каноном ({len(канон)} строк)")
    else:
        ошибка(
            "README РАЗОШЁЛСЯ С КАНОНОМ по таблице статусов",
            [f"нет в README: {з} {н}" for з, н in sorted(канон - в_readme)]
            + [f"лишнее в README: {з} {н}" for з, н in sorted(в_readme - канон)],
        )


# ────────────────────────────────────────────────────────────────────────────
# П8. Диапазоны масштабов совпадают везде и не пересекаются
# Найдено разбором: 5 этапов попадало и в «быстрый», и в «средний».
# ────────────────────────────────────────────────────────────────────────────
def п8_масштабы(тексты: dict[str, str]) -> None:
    диапазоны: dict[str, set[str]] = {}
    for файл in ("README.md", "references/commands.md"):
        найдено = re.findall(r"\|\s*(Быстрый|Средний|Большой)\s*\|\s*([^|]+?)\s*\|", тексты[файл])
        диапазоны[файл] = {f"{м}: {д}" for м, д in найдено}
    значения = list(диапазоны.values())
    if not значения[0]:
        ошибка("ТАБЛИЦА МАСШТАБОВ НЕ НАЙДЕНА", [f"искали в {ф}" for ф in диапазоны])
    elif значения[0] == значения[1]:
        ок("Диапазоны масштабов совпадают в README и commands.md")
    else:
        ошибка(
            "ТАБЛИЦЫ МАСШТАБОВ РАЗОШЛИСЬ",
            [f"{ф}: {sorted(з)}" for ф, з in диапазоны.items()],
        )


# ────────────────────────────────────────────────────────────────────────────
# П9. Каждый ${CLAUDE_PLUGIN_ROOT}/путь существует на диске
# Переименовали папку — ссылка стала вести в никуда, и узнать об этом можно
# было только в бою.
# ────────────────────────────────────────────────────────────────────────────
def п9_пути_существуют(тексты: dict[str, str]) -> None:
    битые = []
    for файл, текст in тексты.items():
        for номер, строка in enumerate(текст.split("\n"), 1):
            # Обратный слэш в конце — не часть пути, а экранированная кавычка
            # из JSON (`…/hook.py\"`). Без него линтер ругался на живые файлы.
            for хвост in re.findall(r"\$\{CLAUDE_PLUGIN_ROOT\}/([^\s`\"'),\\]+)", строка):
                хвост = хвост.rstrip(".,;:")
                if not os.path.exists(путь(хвост)):
                    битые.append(f"{файл}:{номер} → {хвост}")
    if битые:
        ошибка("ССЫЛКА В НИКУДА: путь внутри плагина не существует", битые)
    else:
        ок("Все пути ${CLAUDE_PLUGIN_ROOT}/… существуют на диске")


# ────────────────────────────────────────────────────────────────────────────
# П10. Шапка каждого навыка и агента разбирается, имя совпадает с папкой
# Иначе команда просто не появится в списке, молча.
# ────────────────────────────────────────────────────────────────────────────
def п10_шапки() -> None:
    беды = []
    for папка in sorted(os.listdir(путь("skills"))):
        файл = f"skills/{папка}/SKILL.md"
        if not os.path.isfile(путь(файл)):
            беды.append(f"{файл} — нет файла навыка")
            continue
        поля = frontmatter(читать(файл))
        if поля is None:
            беды.append(f"{файл} — шапка не разбирается")
        elif поля.get("name") != папка:
            беды.append(f"{файл} — name={поля.get('name')!r}, а папка {папка!r}")
        elif not поля.get("description"):
            беды.append(f"{файл} — пустое описание, навык будет не найти")
    for имя in sorted(os.listdir(путь("agents"))):
        поля = frontmatter(читать(f"agents/{имя}"))
        if поля is None:
            беды.append(f"agents/{имя} — шапка не разбирается")
        elif not поля.get("name") or not поля.get("description"):
            беды.append(f"agents/{имя} — нет name или description")
    if беды:
        ошибка("ШАПКИ СЛОМАНЫ — навык или агент не подхватится", беды)
    else:
        ок("Шапки всех навыков и агентов разбираются, имена совпадают с папками")


# ────────────────────────────────────────────────────────────────────────────
# П11. Список команд совпадает с тем, что есть на диске
# Баг Б10: список был написан трижды, README обещал 7 команд, справка — 9.
# ────────────────────────────────────────────────────────────────────────────
def п11_список_команд() -> None:
    на_диске = {п for п in os.listdir(путь("skills")) if os.path.isdir(путь("skills", п))}
    в_справке = set(re.findall(r"/bpd:([a-z]+)", читать("references/commands.md")))
    if на_диске == в_справке:
        ок(f"Справка знает ровно те команды, что есть на диске ({len(на_диске)})")
    else:
        ошибка(
            "ВОЗВРАТ БАГА Б10: список команд разошёлся с диском",
            [f"нет в справке: /bpd:{к}" for к in sorted(на_диске - в_справке)]
            + [f"обещано, но нет папки: /bpd:{к}" for к in sorted(в_справке - на_диске)],
        )


# ────────────────────────────────────────────────────────────────────────────
# П12. Заголовки, которые ищут навыки, есть в шаблонах
# Проверка, которая ищет несуществующий раздел, молча находит пустоту.
# ────────────────────────────────────────────────────────────────────────────
ОБЯЗАТЕЛЬНЫЕ = {
    "templates/PLAN.md": ["## Задачи", "## Чеклист качества"],
    "templates/RESULT.md": ["## Что сделано", "## Созданные и изменённые файлы",
                            "## Принятые решения", "## Отклонения от плана"],
    "templates/CHECK.md": ["## Задачи из плана", "## Заявленные файлы",
                           "## Чеклист качества", "## Итог", "## Замечания"],
    "templates/ROADMAP.md": ["## Этапы", "## Детали этапов", "## Отменённые этапы"],
    "templates/PROJECT.md": ["## Принятые решения"],
    "templates/STATE.md": ["## Проблемы", "## История действий"],
}


def п12_заголовки() -> None:
    беды = []
    for файл, нужные in ОБЯЗАТЕЛЬНЫЕ.items():
        текст = читать(файл)
        for заголовок in нужные:
            if not re.search(rf"^{re.escape(заголовок)}\s*$", текст, re.M):
                беды.append(f"{файл} — нет раздела «{заголовок}»")
    if беды:
        ошибка("В ШАБЛОНЕ НЕТ РАЗДЕЛА, который ищут команды", беды)
    else:
        ок("Все разделы, которые ищут команды, есть в шаблонах")


# ────────────────────────────────────────────────────────────────────────────
# П13. В разделе «## Итог» шаблона нет посторонних слов вердикта
# Ловушка: пояснение с обоими словами стояло внутри раздела, и читатель раздела
# находил «Доработать» в каждом принятом этапе.
# ────────────────────────────────────────────────────────────────────────────
def п13_итог_чистый() -> None:
    тело = раздел(читать("templates/CHECK.md"), "## Итог")
    if тело is None:
        ошибка("В ШАБЛОНЕ CHECK.md НЕТ РАЗДЕЛА «## Итог»", ["оттуда берётся статус этапа"])
        return
    лишние = [с.strip() for с in тело.split("\n")
              if с.strip() and not re.fullmatch(r"\{\{(Принято|Доработать)\}\}", с.strip())]
    if лишние:
        ошибка(
            "РАЗДЕЛ «## Итог» ЗАСОРЁН — в нём есть что-то кроме одного слова",
            лишние + ["Пояснения держать выше заголовка, иначе их прочитают как вердикт."],
        )
    else:
        ок("Раздел «## Итог» в шаблоне содержит ровно одно слово")


# ────────────────────────────────────────────────────────────────────────────
# П14. Правила не переписаны в навыки дословно (предупреждение)
# rules.md обещает: «Ни одно правило отсюда не переписывается в тексты навыков».
# Обещание проверяемо. Ошибкой не делаем: короткое совпадение бывает случайным,
# а сторож, который кричит на случайность, читать перестают.
# ────────────────────────────────────────────────────────────────────────────
def п14_копии_правил(тексты: dict[str, str]) -> None:
    правила = тексты["references/rules.md"]
    кандидаты = [с.strip() for с in правила.split("\n")
                 if len(с.strip()) >= 60 and not с.strip().startswith(("|", "#", ">", "-", "`"))]
    копии = []
    for фраза in кандидаты:
        for файл, текст in тексты.items():
            if файл != "references/rules.md" and фраза in текст:
                копии.append(f"{файл}: «{фраза[:70]}…»")
    if копии:
        предупредить(
            f"ПРАВИЛА ПЕРЕПИСАНЫ В ДРУГИЕ ФАЙЛЫ ({len(копии)}) — копия разойдётся с оригиналом",
            копии[:15] + ([f"…и ещё {len(копии) - 15}"] if len(копии) > 15 else []),
        )
    else:
        ок("Ни одно правило не переписано в навыки дословно")


# ────────────────────────────────────────────────────────────────────────────
# П15. В bash-скриптах переменная перед русской буквой обрамлена скобками
# Родной bash macOS — 3.2, и он не многобайтный: байты русской кавычки он
# считает частью имени, и "$h»" превращается в переменную «h»» → «unbound
# variable» на ровном месте. Видно только на той самой строке и только на 3.2,
# поэтому ловим глазами машины, а не человека.
# ────────────────────────────────────────────────────────────────────────────
ГОЛАЯ_ПЕРЕМЕННАЯ = re.compile(r"\$[a-zA-Z_][a-zA-Z_0-9]*(?=[^\x00-\x7F])")


def п15_переменные_в_скриптах() -> None:
    беды = []
    for корень_обхода, папки, файлы in os.walk(КОРЕНЬ):
        папки[:] = [п for п in папки if п not in (".git", "__pycache__")]
        for имя in файлы:
            if not имя.endswith(".sh") and имя != "bpd-validate":
                continue
            полный = os.path.join(корень_обхода, имя)
            относительный = os.path.relpath(полный, КОРЕНЬ)
            try:
                with open(полный, encoding="utf-8") as ф:
                    строки = ф.read().split("\n")
            except OSError as беда:
                сдаться(f"не прочитать {относительный}: {беда}")
                return
            for номер, строка in enumerate(строки, 1):
                for найдено in ГОЛАЯ_ПЕРЕМЕННАЯ.findall(строка):
                    беды.append(f"{относительный}:{номер} — {найдено} перед не-ASCII, "
                                f"нужно ${{{найдено[1:]}}}")
    if беды:
        ошибка("ПЕРЕМЕННАЯ БЕЗ СКОБОК ПЕРЕД РУССКОЙ БУКВОЙ — bash 3.2 съест её "
               "вместе с буквой", беды)
    else:
        ок("В bash-скриптах переменные перед русским текстом обрамлены")


