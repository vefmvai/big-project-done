#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Линтер репозитория BPD: сторож, который проверяет сам плагин.

Это НЕ валидатор проектов пользователя (тот проверяет папку `.bpd/` и лежит
в `scripts/validate.py`). Здесь проверяется исходник плагина — те правила,
которые должны выполняться в самих файлах BPD и которые уже один раз были
нарушены молча.

Каждая проверка соответствует конкретному багу, найденному вживую 12.08.2026.
Проверка без истории тут не заводится: сторож, который кричит на выдуманное,
перестают читать.

Коды возврата — как у валидатора, и это намеренно:
    0  — чисто
    1  — найдены ошибки
    2  — прогон НЕ СОСТОЯЛСЯ (упали, не нашли репозиторий, не прочитали файл)

Код 2 существует ровно затем, чтобы «нечем было проверить» не выглядело как
«всё хорошо». Невыполненная проверка не должна быть неотличима от пройденной.

Запуск:  python3 tests/lint-plugin.py [путь к корню плагина]
"""

from __future__ import annotations

import json
import os
import re
import sys

# Печатаем через replace: консоль в cp1251 не должна ронять прогон и
# превращать «нашлись ошибки» в «прогон упал».
for поток in (sys.stdout, sys.stderr):
    try:
        поток.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError, OSError):
        pass

КОРЕНЬ = ""
ошибки: list[str] = []
предупреждения: list[str] = []
пройдено: list[str] = []


def ошибка(заголовок: str, строки: list[str]) -> None:
    ошибки.append(заголовок)
    print(f"❌ {заголовок}")
    for с in строки:
        print(f"    • {с}")
    print()


def предупредить(заголовок: str, строки: list[str]) -> None:
    предупреждения.append(заголовок)
    print(f"⚠️  {заголовок}")
    for с in строки:
        print(f"    • {с}")
    print()


def ок(текст: str) -> None:
    пройдено.append(текст)
    print(f"✅ {текст}")


def путь(*части: str) -> str:
    return os.path.join(КОРЕНЬ, *части)


def читать(относительный: str) -> str:
    """Прочитать файл. Не смог — это код 2, а не «проверка прошла»."""
    полный = путь(относительный)
    try:
        with open(полный, encoding="utf-8") as ф:
            return ф.read()
    except FileNotFoundError:
        сдаться(f"нет файла {относительный} — проверять нечего")
    except OSError as беда:
        сдаться(f"не прочитать {относительный}: {беда}")
    return ""


def сдаться(причина: str) -> None:
    print(f"\nОШИБКА: {причина}.", file=sys.stderr)
    print("    Это НЕ «плагин в порядке»: проверки не выполнялись.", file=sys.stderr)
    sys.exit(2)


def все_тексты() -> dict[str, str]:
    """Все текстовые файлы плагина: путь → содержимое. Тесты не считаются."""
    собрано = {}
    for корень, папки, файлы in os.walk(КОРЕНЬ):
        папки[:] = [п for п in папки if п not in (".git", "tests", "__pycache__")]
        for имя in файлы:
            if not имя.endswith((".md", ".json")):
                continue
            полный = os.path.join(корень, имя)
            относительный = os.path.relpath(полный, КОРЕНЬ)
            try:
                with open(полный, encoding="utf-8") as ф:
                    собрано[относительный] = ф.read()
            except OSError as беда:
                сдаться(f"не прочитать {относительный}: {беда}")
    return собрано


def frontmatter(текст: str) -> dict[str, str] | None:
    """Разбор шапки markdown. Только верхнеуровневые ключи — их и проверяем."""
    if not текст.startswith("---\n"):
        return None
    конец = текст.find("\n---", 3)
    if конец == -1:
        return None
    поля: dict[str, str] = {}
    ключ = None
    for строка in текст[4:конец].split("\n"):
        совпало = re.match(r"^([a-zA-Z0-9_-]+):\s*(.*)$", строка)
        if совпало:
            ключ = совпало.group(1)
            поля[ключ] = совпало.group(2).strip()
        elif ключ and строка.startswith(("  ", "\t")):
            поля[ключ] = (поля[ключ] + " " + строка.strip()).strip()
    return поля


def раздел(текст: str, заголовок: str) -> str | None:
    """Содержимое раздела `## Заголовок` до следующего заголовка того же уровня."""
    начало = re.search(rf"^{re.escape(заголовок)}\s*$", текст, re.M)
    if not начало:
        return None
    хвост = текст[начало.end():]
    следующий = re.search(r"^##\s", хвост, re.M)
    return хвост[: следующий.start()] if следующий else хвост


